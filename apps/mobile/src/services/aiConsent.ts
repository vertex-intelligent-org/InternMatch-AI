let activePrompt: Promise<boolean> | null = null;

function getCopy(): ConsentCopy {
  const locale =
    normalizeLocale(i18n.resolvedLanguage || i18n.language) || 'en';

  return COPY[locale as 'en' | 'tr' | 'ar'] || COPY.en;
}

async function getStorageKey(): Promise<string> {
  const { data } = await supabase.auth.getSession();
  const userId = data.session?.user?.id || 'signed-out';

  return `${STORAGE_PREFIX}:${CONSENT_VERSION}:${userId}`;
}

async function hasStoredConsent(): Promise<boolean> {
  try {
    const key = await getStorageKey();
    const raw = await AsyncStorage.getItem(key);

    if (!raw) return false;

    const parsed = JSON.parse(raw) as Partial<ConsentRecord>;

    return (
      parsed.granted === true &&
      parsed.version === CONSENT_VERSION
    );
  } catch {
    return false;
  }
}

async function persistGrantedConsent(): Promise<void> {
  const key = await getStorageKey();

  const record: ConsentRecord = {
    granted: true,
    version: CONSENT_VERSION,
    granted_at: new Date().toISOString(),
  };

  await AsyncStorage.setItem(
    key,
    JSON.stringify(record)
  );
}

export async function ensureAIProcessingConsent(): Promise<boolean> {
  if (await hasStoredConsent()) {
    return true;
  }

  if (activePrompt) {
    return activePrompt;
  }

  const copy = getCopy();

  activePrompt = new Promise<boolean>((resolve) => {
    const finish = (value: boolean) => {
      activePrompt = null;
      resolve(value);
    };

    Alert.alert(
      copy.title,
      copy.message,
      [
        {
          text: copy.notNow,
          style: 'cancel',
          onPress: () => finish(false),
        },
        {
          text: copy.allow,
          onPress: async () => {
            try {
              await persistGrantedConsent();
            } catch {
              // Consent was still explicitly granted for this invocation.
              // Failure to persist means the app will ask again next time.
            }

            finish(true);
          },
        },
      ],
      {
        cancelable: false,
      }
    );
  });

  return activePrompt;
}

export async function revokeAIProcessingConsent(): Promise<void> {
  try {
    const key = await getStorageKey();
    await AsyncStorage.removeItem(key);
  } catch {
    // Fail closed: a missing/unreadable consent record means consent
    // will be requested again before another AI-triggering action.
  }
}
